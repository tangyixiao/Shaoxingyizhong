ROOT = Path(__file__).resolve().parents[1]


class Images(HTMLParser):
    def __init__(self, text):
        super().__init__()
        self.images = []
        self.feed(text)

    def handle_starttag(self, tag, attrs):
        if tag == "img":
            self.images.append(dict(attrs))


class ImagePreviewTests(unittest.TestCase):
    def routes(self, limit=20_000):
        data = json.loads((ROOT / "attachment_routes.json").read_text())
        data["cdn_max_file_bytes"] = limit
        data["overrides"] = {}
        data["image_previews"] = {}
        data["preview_repository"] = "archive-previews"
        return attachment_routing.RouteConfig(data)

    def image(self, root, suffix):
        image = root / ("UploadFiles/xwzx/2026/7/noise" + suffix)
        image.parent.mkdir(parents=True)
        ppm = root / "noise.ppm"
        ppm.write_bytes(b"P6\n128 128\n255\n" + random.Random(42).randbytes(128 * 128 * 3))
        target = str(image) + ("[Q=100]" if suffix == ".jpg" else "")
        subprocess.run(["vips", "copy", str(ppm), target], check=True)
        return image

    @unittest.skipUnless(shutil.which("vips"), "libvips is required")
    def test_inventory_keeps_original_bytes_and_adds_near_limit_png_preview(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            source = root / "source"
            original = self.image(source, ".png")
            before = original.read_bytes()
            routes = self.routes()
            entries = sync_image_shards.build_inventory(source, routes, root / "workspace")
            self.assertEqual(len(entries), 2)
            archived = next(e for e in entries if e.target_path.endswith("noise.png"))
            preview = next(e for e in entries if e != archived)
            self.assertEqual(archived.prepared_path.read_bytes(), before)
            self.assertEqual(original.read_bytes(), before)
            self.assertEqual(archived.sha256, hashlib.sha256(before).hexdigest())
            self.assertLessEqual(preview.size, 20_000)
            self.assertGreater(preview.size, 19_000)
            self.assertTrue(routes.resolve(archived.source_path).fallback_url)
            # A warm run reuses the generated bytes instead of re-encoding.
            with mock.patch.object(sync_image_shards, "create_cdn_preview", side_effect=AssertionError("unexpected re-encode")):
                again = sync_image_shards.build_inventory(source, routes, root / "workspace")
            self.assertEqual([e.sha256 for e in entries], [e.sha256 for e in again])

